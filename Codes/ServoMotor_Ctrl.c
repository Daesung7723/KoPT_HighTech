/*
 * ============================================================
 *  ATmega128 서보 모터 자동 시퀀스 제어 실습 코드
 * ============================================================
 *
 * [동작 개요]
 *  Timer3의 Fast PWM 출력(OC3A)으로 서보 모터를 제어한다.
 *  아래 시퀀스를 무한 반복하며, 각 위치에서 2초간 유지한다.
 *
 *  -90° → 0° → +90° → 0° → -90° → ... (무한 반복)
 *
 * [서보 모터 제어 원리]
 *  서보 모터는 20ms(50Hz) 주기의 PWM 신호에서
 *  High 구간(펄스 폭)의 길이로 각도를 결정한다.
 *
 *  펄스 폭과 각도의 관계 (실측값 기준):
 *   0.5ms → -90°  (좌측 끝)
 *   1.5ms →   0°  (중립, 정면)
 *   2.5ms → +90°  (우측 끝)
 *
 *  ※ 표준 규격(1.0~2.0ms)에서 실제 동작이 ±45°에 그치므로
 *     0.5~2.5ms로 범위를 확장하여 ±90° 풀 레인지를 확보한다.
 *     서보 모델에 따라 다를 수 있으므로 실측 후 조정할 것.
 *
 * [하드웨어 연결]
 *  PE3 (OC3A) → 서보 모터 신호선 (황색/주황색)
 *  VCC (5V)   → 서보 모터 전원선 (적색)
 *  GND        → 서보 모터 접지선 (갈색/흑색)
 *
 * [PWM 주파수 계산]
 *  F_PWM = F_CPU / (Prescaler × (ICR3 + 1))
 *        = 16,000,000 / (8 × 40,000)
 *        = 50Hz  →  주기 T = 20ms  ✅ 서보 모터 표준 주기
 *
 * [OCR3A 값 계산]
 *  OCR3A = 펄스폭(μs) × F_CPU / (Prescaler × 1,000,000)
 *        = 펄스폭(μs) × 16,000,000 / (8 × 1,000,000)
 *        = 펄스폭(μs) × 2
 *
 *   -90° → 500μs × 2  = OCR3A 1000
 *     0° → 1500μs × 2 = OCR3A 3000
 *   +90° → 2500μs × 2 = OCR3A 5000
 * ============================================================
 */

/* F_CPU: AVR 클록 주파수 정의.
   _delay_ms() / _delay_us() 계산에 사용되므로
   반드시 #include 이전에 선언해야 한다. */
#define F_CPU 16000000UL

#include <avr/io.h>      // AVR 레지스터/비트 이름 정의 (DDRE, TCCR3A 등)
#include <util/delay.h>  // _delay_ms(), _delay_us() 함수 제공

/* ============================================================
 *  [1] 서보 모터 PWM 관련 상수 정의
 * ============================================================ */

/* OC3A 출력 핀: PE3 (ATmega128 Timer3 Compare Match A 출력)
   서보 모터의 신호선을 이 핀에 연결한다. */
#define SERVO_PWM_DDR   DDRE    // OC3A 핀이 속한 포트의 DDR
#define SERVO_PWM_PIN   PE3     // OC3A = PORTE 비트 3

/* ICR3 (TOP 값) 설정
 *  Fast PWM Mode 14에서 카운터는 0부터 ICR3까지 증가 후 0으로 복귀.
 *  ICR3 = (F_CPU / Prescaler / F_PWM) - 1
 *       = (16,000,000 / 8 / 50) - 1
 *       = 40,000 - 1 = 39,999 */
#define SERVO_ICR_TOP   39999   // PWM 주기: 20ms (50Hz)

/* OCR3A 값 = 원하는 펄스 폭(μs) × 2
 *  각도별 OCR3A 상수 (실측 보정값 적용) */
#define SERVO_OCR_NEG90     1000    // -90°: 펄스 폭 500μs  (0.5ms)
#define SERVO_OCR_ZERO      3000    //   0°: 펄스 폭 1500μs (1.5ms) ← 중립
#define SERVO_OCR_POS90     5000    // +90°: 펄스 폭 2500μs (2.5ms)

/* ============================================================
 *  [2] 시퀀스 배열 정의
 * ============================================================
 *
 *  servo_ocr_seq[]  : 각 단계에서 OCR3A에 쓸 값 (서보 위치)
 *
 *  시퀀스 흐름:
 *   단계 0 → 단계 1 → 단계 2 → 단계 3 → 단계 0 → ...
 *    -90°  →    0°  →   +90° →    0°  →  -90°  → ...
 *
 *  단계를 추가하거나 순서를 바꾸려면 이 배열만 수정하면 된다.
 *  SEQ_LENGTH도 배열 크기에 맞게 함께 수정해야 한다.
 */
#define SEQ_LENGTH  4   // 시퀀스 총 단계 수

const uint16_t servo_ocr_seq[SEQ_LENGTH] = {
    SERVO_OCR_NEG90,    // 단계 0: -90°
    SERVO_OCR_ZERO,     // 단계 1:   0°
    SERVO_OCR_POS90,    // 단계 2: +90°
    SERVO_OCR_ZERO      // 단계 3:   0°
};

/* ============================================================
 *  [3] 유지 시간 정의
 * ============================================================
 *
 *  avr-libc의 _delay_ms()는 인수가 컴파일 타임 상수(리터럴)일 때만
 *  정확하게 동작한다. 변수를 인수로 사용하면 오차가 발생한다.
 *
 *  따라서 고정 단위(DELAY_UNIT_MS = 100ms)를 HOLD_LOOP_COUNT회
 *  반복하는 방식으로 2000ms(2초)를 구현한다.
 *   100ms × 20회 = 2000ms
 */
#define HOLD_TIME_MS        2000    // 각 위치 유지 목표 시간 (ms)
#define DELAY_UNIT_MS       100     // _delay_ms()에 전달할 고정 단위 (ms)
#define HOLD_LOOP_COUNT     (HOLD_TIME_MS / DELAY_UNIT_MS)  // = 20회

/* ============================================================
 *  [4] 함수 프로토타입 선언
 * ============================================================ */
void init_ports(void);
void init_timer3_pwm_servo(void);
void servo_set(uint16_t ocr_value);

/* ============================================================
 *  [5] main 함수
 * ============================================================ */
int main(void)
{
    /* 시스템 초기화 */
    init_ports();               // 포트 입출력 방향 설정
    init_timer3_pwm_servo();    // Timer3 PWM 초기화 (50Hz)

    /* 시퀀스 인덱스 변수
     *  0 ~ SEQ_LENGTH-1 범위를 순환하며 현재 단계를 나타낸다. */
    uint8_t step = 0;

    /* 시작 위치: 단계 0 (-90°)로 이동 */
    servo_set(servo_ocr_seq[step]);

    /* ============================================================
     *  메인 루프 (무한 반복)
     * ============================================================
     *
     *  매 루프마다 수행하는 작업:
     *   [Step 1] 현재 위치에서 2초 유지
     *   [Step 2] 다음 단계 인덱스 계산 (순환)
     *   [Step 3] 서보를 다음 위치로 이동
     */
    while (1)
    {
        /* [Step 1] 현재 위치 2초 유지
         *
         *  _delay_ms(100)을 20회 반복 = 2000ms
         *  DELAY_UNIT_MS는 컴파일 타임 상수이므로 오차 없이 동작한다. */
        for (uint8_t i = 0; i < HOLD_LOOP_COUNT; i++) {
            _delay_ms(DELAY_UNIT_MS);   // 100ms 대기 × 20회 = 2초
        }

        /* [Step 2] 다음 단계 인덱스 계산
         *
         *  % 연산(나머지)으로 0 ~ SEQ_LENGTH-1 범위를 순환한다.
         *  예) step = 3 → (3+1) % 4 = 0  (처음으로 돌아감)
         *      step = 0 → (0+1) % 4 = 1  (다음 단계로 전진) */
        step = (step + 1) % SEQ_LENGTH;

        /* [Step 3] 서보를 다음 위치로 이동
         *
         *  OCR3A를 갱신하면 현재 진행 중인 PWM 주기가 끝난 후
         *  다음 주기(20ms 이내)부터 새로운 펄스 폭이 출력된다. */
        servo_set(servo_ocr_seq[step]);
    }

    return 0;   // ATmega128에서는 실제로 도달하지 않음 (컴파일러 경고 방지)
}

/* ============================================================
 *  [6] 포트 초기화 함수
 * ============================================================
 *
 *  OC3A(PE3) 핀만 출력으로 설정한다.
 *  DDRE의 해당 비트만 1로 설정하고 나머지는 보존한다.
 *  (|= 연산 사용 → 다른 비트에 영향 없음)
 */
void init_ports(void)
{
    DDRE |= (1 << SERVO_PWM_PIN);   // PE3 = 출력 (OC3A PWM 신호 출력용)
}

/* ============================================================
 *  [7] Timer3 Fast PWM 초기화 함수
 * ============================================================
 *
 *  [Fast PWM Mode 14 동작 원리]
 *   카운터(TCNT3)가 0(BOTTOM)에서 ICR3(TOP)까지 증가한 후
 *   다시 0으로 복귀하는 단방향 카운팅을 반복한다.
 *
 *   OC3A 핀 출력 (비반전 모드, COM3A1=1, COM3A0=0):
 *    - TCNT3 == BOTTOM(0)  : OC3A → High  (펄스 시작)
 *    - TCNT3 == OCR3A      : OC3A → Low   (펄스 종료)
 *
 *   → OCR3A 값이 클수록 High 구간이 길어져 펄스 폭이 증가한다.
 *
 *  [레지스터 설정 요약]
 *   TCCR3A: WGM31=1, COM3A1=1
 *   TCCR3B: WGM33=1, WGM32=1, CS31=1 (Prescaler 8)
 *   ICR3  = 39999  → 주기 20ms (50Hz)
 *   OCR3A = 초기값 → 서보 시작 위치
 *
 *  ※ TCCR3B에 CS 비트를 마지막에 설정하여 타이머를 가장 나중에
 *    시작시키면 초기화 중 불완전한 PWM 신호 출력을 방지할 수 있다.
 */
void init_timer3_pwm_servo(void)
{
    /* Fast PWM Mode 14 설정
     *  WGM3[3:0] = 0b1110 → Mode 14 (Fast PWM, TOP = ICR3)
     *  WGM31: TCCR3A 레지스터의 비트 1
     *  WGM32: TCCR3B 레지스터의 비트 3
     *  WGM33: TCCR3B 레지스터의 비트 4 */
    TCCR3A |= (1 << WGM31);
    TCCR3B |= (1 << WGM33) | (1 << WGM32);

    /* OC3A 핀 비반전 출력 모드 설정
     *  COM3A1=1, COM3A0=0 → 비반전(Non-Inverting) Fast PWM
     *  OCR3A에 일치할 때 Low, BOTTOM에서 High */
    TCCR3A |= (1 << COM3A1);

    /* PWM 주기 설정 (TOP 값)
     *  ICR3 = 39999 → F_PWM = 16MHz / (8 × 40000) = 50Hz (20ms) */
    ICR3 = SERVO_ICR_TOP;

    /* 초기 위치: -90° (단계 0)
     *  CS 비트 설정(타이머 시작) 전에 OCR3A를 먼저 설정한다. */
    OCR3A = SERVO_OCR_NEG90;

    /* Prescaler 8 선택 → 타이머 카운팅 시작
     *  CS3[2:0] = 010 → Prescaler 8 (CS31=1, CS30=0, CS32=0)
     *  이 비트가 설정되는 순간부터 PWM 신호가 출력된다. */
    TCCR3B |= (1 << CS31);
}

/* ============================================================
 *  [8] 서보 모터 위치 설정 함수
 * ============================================================
 *
 *  매개변수 ocr_value: OCR3A에 쓸 값
 *   SERVO_OCR_NEG90(1000) ~ SERVO_OCR_POS90(5000) 범위
 *
 *  OCR3A에 값을 쓰면 현재 PWM 주기가 끝난 후 다음 주기부터
 *  새로운 펄스 폭이 자동으로 적용된다. (하드웨어가 자동 처리)
 *
 *  사용 예:
 *   servo_set(SERVO_OCR_NEG90);  // -90°로 이동
 *   servo_set(SERVO_OCR_ZERO);   //   0°로 이동 (중립)
 *   servo_set(SERVO_OCR_POS90);  // +90°로 이동
 */
void servo_set(uint16_t ocr_value)
{
    OCR3A = ocr_value;  // PWM 비교 매치 레지스터에 펄스 폭 값 저장
}